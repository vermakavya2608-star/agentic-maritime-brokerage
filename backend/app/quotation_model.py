from datetime import datetime
from sqlalchemy import Column, Integer, String, Float, DateTime, ForeignKey, JSON
from sqlalchemy.orm import Mapped, mapped_column
from .database import Base

class QuotationRecord(Base):
    __tablename__ = "quotations"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    user_id: Mapped[int] = mapped_column(Integer, ForeignKey("users.id"), index=True)
    
    # Core Shipment details
    origin: Mapped[str] = mapped_column(String(100), nullable=False)
    destination: Mapped[str] = mapped_column(String(100), nullable=False)
    cargo_type: Mapped[str] = mapped_column(String(100), nullable=False)
    containers: Mapped[int] = mapped_column(Integer, nullable=False)
    
    # Financial & AI Metrics
    total_freight_usd: Mapped[float] = mapped_column(Float, nullable=False)
    route_score: Mapped[float] = mapped_column(Float, nullable=False)
    
    # Lifecycle State
    status: Mapped[str] = mapped_column(String(50), default="Pending Review", nullable=False)
    feedback: Mapped[str] = mapped_column(String(500), nullable=True)
    
    # The full JSON payload generated by the AI Agents
    full_data: Mapped[dict] = mapped_column(JSON, nullable=False)
    
    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow, nullable=False)
    updated_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow, nullable=False)